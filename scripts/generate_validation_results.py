#!/usr/bin/env python3
"""
scripts/generate_validation_results.py
======================================
Regenerate every published validation figure from the demo data in `data/`.

Why this exists
---------------
The results previously quoted in the README were computed on a four-asset
SPY/QQQ/TLT/GLD portfolio that was never committed to the repository — the
shipped demo file holds different instruments entirely. Anyone cloning the
project therefore could not reproduce a single published number, which is the
one thing a model validator will actually try to do.

Every figure in `docs/validation_results.md` is now produced by this script from
`data/market_data.csv` and `data/credit_example.csv`. All random draws are
seeded, so the output is deterministic.

Usage
-----
    python scripts/generate_validation_results.py           # regenerate
    python scripts/generate_validation_results.py --check   # verify, exit 1 on drift

CI runs `--check`, so published results cannot silently drift away from the code
that produced them.
"""

from __future__ import annotations

import argparse
import sys
from datetime import date
from pathlib import Path

import numpy as np
import pandas as pd

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from risklib.credit import compute_el_table, summarize_el          # noqa: E402
from risklib.data import load_prices, to_returns                   # noqa: E402
from risklib.market import (                                       # noqa: E402
    DEFAULT_DURATIONS,
    MarketRiskConfig,
    MarketRiskModel,
    backtest_var_fhs,
    backtest_var_historical,
    erc_weights,
    scenario_corr_bump_mc,
    scenario_covariance_scale,
    scenario_equities_shock,
    scenario_rates_bp,
    var_parametric_normal_parts,
)

DATA = ROOT / "data"
OUT = ROOT / "docs" / "validation_results.md"

EXPOSURE = 1_000_000.0
SEED = 42
N_SIMS = 100_000
WINDOW = 250
ALPHAS = (0.95, 0.975, 0.99)
TRADING_DAYS = 252

# Relative tolerance for the Euler summation identity. Component VaR must sum to
# portfolio VaR to within this bound on any platform; the residual itself is
# machine noise and is deliberately not published.
EULER_TOL = 1e-9

METHOD_LABELS = {
    "historical": "Historical Simulation",
    "parametric": "Parametric (Normal)",
    "monte_carlo": "Monte Carlo",
    "fhs": "Filtered Historical (GARCH, fixed)",
}


def verdict(p: float) -> str:
    return "PASS" if p > 0.05 else "FAIL"


def build_report() -> str:
    prices = load_prices(DATA / "market_data.csv")
    returns = to_returns(prices, method="log")
    tickers = list(returns.columns)
    weights = np.ones(len(tickers)) / len(tickers)

    L: list[str] = []
    add = L.append

    add("# Validation Results")
    add("")
    add("> **Generated by `scripts/generate_validation_results.py`. Do not edit by hand.**")
    add("> Every figure below is reproducible from the data committed in `data/`:")
    add("> `python scripts/generate_validation_results.py`")
    add("")

    # ------------------------------------------------------------------
    add("## Test portfolio")
    add("")
    add(f"- **Instruments:** {', '.join(tickers)} (equal-weighted, "
        f"{1 / len(tickers):.1%} each)")
    add(f"- **Exposure:** ${EXPOSURE:,.0f}")
    add(f"- **Sample:** {returns.index.min():%Y-%m-%d} to {returns.index.max():%Y-%m-%d} "
        f"({len(returns):,} daily log-return observations)")
    add(f"- **Monte Carlo:** {N_SIMS:,} paths, seed {SEED}")
    add(f"- **Backtest window:** {WINDOW} trading days")
    add("")

    r_p = pd.Series(returns.values @ weights, index=returns.index)
    ann_ret = float(r_p.mean() * TRADING_DAYS)
    ann_vol = float(r_p.std(ddof=1) * np.sqrt(TRADING_DAYS))

    add("### Portfolio statistics")
    add("")
    add("| Metric | Value |")
    add("|---|---:|")
    add(f"| Annualised return | {ann_ret:.2%} |")
    add(f"| Annualised volatility | {ann_vol:.2%} |")
    add(f"| Sharpe ratio (RF = 0) | {ann_ret / ann_vol:.2f} |")
    for t in tickers:
        v = float(returns[t].std(ddof=1) * np.sqrt(TRADING_DAYS))
        add(f"| {t} annualised volatility | {v:.2%} |")
    add("")

    add("### Correlation matrix")
    add("")
    corr = returns.corr()
    add("| | " + " | ".join(tickers) + " |")
    add("|---|" + "---:|" * len(tickers))
    for t in tickers:
        add(f"| **{t}** | " + " | ".join(f"{corr.loc[t, c]:.3f}" for c in tickers) + " |")
    add("")

    # ------------------------------------------------------------------
    add("## 1. Point risk measures (1-day horizon)")
    add("")
    add("| Method | VaR 95% | ES 95% | VaR 99% | ES 99% |")
    add("|---|---:|---:|---:|---:|")
    for method, label in METHOD_LABELS.items():
        cells = []
        for a in (0.95, 0.99):
            cfg = MarketRiskConfig(alpha=a, method=method, horizon_days=1,
                                   exposure=EXPOSURE, n_sims=N_SIMS, seed=SEED)
            m = MarketRiskModel(returns, weights, cfg).fit()
            cells += [f"${m.compute_var():,.0f}", f"${m.compute_es():,.0f}"]
        add(f"| {label} | {cells[0]} | {cells[1]} | {cells[2]} | {cells[3]} |")

    # MLE row
    mle_cells = []
    for a in (0.95, 0.99):
        cfg = MarketRiskConfig(alpha=a, method="fhs", horizon_days=1,
                               exposure=EXPOSURE, fit_garch=True)
        m = MarketRiskModel(returns, weights, cfg).fit()
        mle_cells += [f"${m.compute_var():,.0f}", f"${m.compute_es():,.0f}"]
    add(f"| Filtered Historical (GARCH, MLE) | {mle_cells[0]} | {mle_cells[1]} | "
        f"{mle_cells[2]} | {mle_cells[3]} |")
    add("")
    add("ES exceeds VaR at every confidence level for every method, as the loss-convention "
        "invariant in `MarketRiskModel.fit()` requires.")
    add("")

    # ------------------------------------------------------------------
    add("## 2. GARCH(1,1) parameters — assumed vs estimated")
    add("")
    cfg_fixed = MarketRiskConfig(method="fhs", alpha=0.99, exposure=EXPOSURE, fit_garch=False)
    cfg_mle = MarketRiskConfig(method="fhs", alpha=0.99, exposure=EXPOSURE, fit_garch=True)
    fi_fixed = MarketRiskModel(returns, weights, cfg_fixed).fit().fit_info_
    m_mle = MarketRiskModel(returns, weights, cfg_mle).fit()
    fi_mle = m_mle.fit_info_

    add("| Parameter | Fixed (variance targeting) | MLE |")
    add("|---|---:|---:|")
    add(f"| omega | {fi_fixed['omega']:.3e} | {fi_mle['omega']:.3e} |")
    add(f"| alpha (ARCH) | {fi_fixed['alpha_g']:.4f} | {fi_mle['alpha_g']:.4f} |")
    add(f"| beta (GARCH) | {fi_fixed['beta_g']:.4f} | {fi_mle['beta_g']:.4f} |")
    add(f"| persistence | {fi_fixed['persistence']:.4f} | {fi_mle['persistence']:.4f} |")
    add(f"| long-run volatility (ann.) | {fi_fixed['long_run_vol']:.2%} | "
        f"{fi_mle['long_run_vol']:.2%} |")
    add(f"| log-likelihood | — | {fi_mle['log_likelihood']:,.1f} |")
    add(f"| AIC / BIC | — | {fi_mle['aic']:,.1f} / {fi_mle['bic']:,.1f} |")
    add("")
    add(f"The assumed parameters imply persistence of {fi_fixed['persistence']:.4f}; the "
        f"estimated value is {fi_mle['persistence']:.4f}. The fixed convention therefore "
        "overstates volatility persistence on this sample, which is precisely the "
        "misspecification the MLE path was added to address.")
    add("")
    add("**Assumptions reported by the model object under MLE:**")
    add("")
    for a in m_mle.assumptions():
        add(f"- {a}")
    add("")

    # ------------------------------------------------------------------
    add("## 3. Backtesting")
    add("")
    add("Thresholds use information available strictly through *t−1*. Three tests are "
        "reported: **Kupiec POF** (unconditional coverage), **Christoffersen** "
        "(independence / no clustering), and **joint conditional coverage** "
        "(LR_cc = LR_uc + LR_ind ~ chi-squared with 2 df).")
    add("")

    for name, fn in (("Rolling Historical Simulation", backtest_var_historical),
                     ("Rolling Filtered Historical Simulation", backtest_var_fhs)):
        add(f"### {name} ({WINDOW}-day window)")
        add("")
        add("| α | T | Exc. | Hit % | Exp. % | Kupiec LR | p | Christ. LR | p | "
            "Joint LR | p | Result |")
        add("|---|---:|---:|---:|---:|---:|---:|---:|---:|---:|---:|---|")
        for a in ALPHAS:
            b = fn(returns, weights, alpha=a, window=WINDOW)
            allp = min(b["kupiec_pvalue"], b["christoffersen_pvalue"], b["joint_pvalue"])
            add(f"| {a:.1%} | {b['T']:,} | {b['exceedances']} | {b['hit_rate'] * 100:.2f}% | "
                f"{(1 - a) * 100:.2f}% | {b['kupiec_LR']:.3f} | {b['kupiec_pvalue']:.4f} | "
                f"{b['christoffersen_LR']:.3f} | {b['christoffersen_pvalue']:.4f} | "
                f"{b['joint_LR']:.3f} | {b['joint_pvalue']:.4f} | {verdict(allp)} |")
        add("")

    b95 = backtest_var_historical(returns, weights, alpha=0.95, window=WINDOW)
    tr = b95["transitions"]
    add("**Exception transition counts (Historical, α = 95%)**")
    add("")
    add("| | → no exception | → exception |")
    add("|---|---:|---:|")
    add(f"| **no exception →** | {tr['n00']} | {tr['n01']} |")
    add(f"| **exception →** | {tr['n10']} | {tr['n11']} |")
    add("")
    add(f"P(exception | no exception) = {tr['pi_01']:.4f}; "
        f"P(exception | exception) = {tr['pi_11']:.4f}. Under independence these are "
        "approximately equal; a materially larger second figure indicates clustering.")
    add("")

    # ------------------------------------------------------------------
    add("## 4. VaR decomposition — Euler allocation (Normal, α = 95%)")
    add("")
    parts = var_parametric_normal_parts(returns, weights, alpha=0.95,
                                        horizon_days=1, exposure=EXPOSURE)
    add("| Instrument | Weight | Marginal VaR | Component VaR | % of VaR |")
    add("|---|---:|---:|---:|---:|")
    for t, w, mv, cv, pc in zip(tickers, parts["w"], parts["mVaR"],
                                parts["cVaR"], parts["pContrib"]):
        add(f"| {t} | {w:.1%} | ${mv:,.0f} | ${cv:,.0f} | {pc * 100:.1f}% |")
    add(f"| **Total** | **100.0%** | | **${parts['cVaR'].sum():,.0f}** | "
        f"**{parts['pContrib'].sum() * 100:.1f}%** |")
    add("")
    # The Euler residual is exactly the kind of number that must NOT be published:
    # its value is pure floating-point noise and varies with CPU architecture and
    # BLAS backend (observed: 3.6e-12 on Linux/OpenBLAS, 0.0 on Apple Accelerate).
    # Printing it made the reproducibility check fail across platforms for no real
    # reason. Assert the bound instead, and publish the bound.
    euler_residual = abs(float(parts["cVaR"].sum()) - float(parts["VaR"]))
    euler_rel = euler_residual / abs(parts["VaR"]) if parts["VaR"] else 0.0
    if euler_rel >= EULER_TOL:
        raise AssertionError(
            f"Euler identity violated: component VaR sums to {parts['cVaR'].sum():.10f} "
            f"against portfolio VaR {parts['VaR']:.10f} (relative error {euler_rel:.2e}, "
            f"tolerance {EULER_TOL:.0e}). This is a real decomposition error, not noise."
        )
    add(f"Component VaR sums to ${parts['cVaR'].sum():,.2f} against a portfolio VaR of "
        f"${parts['VaR']:,.2f} — agreement to within {EULER_TOL:.0e} relative, verified "
        "when this report is generated. The identity is exact, not approximate: VaR is "
        "homogeneous of degree 1 in the weights, so Euler's theorem holds with equality.")
    add("")

    # ------------------------------------------------------------------
    add("## 5. Risk budgeting — Equal Risk Contribution")
    add("")
    w_erc, info = erc_weights(returns, horizon_days=1, tol=1e-10)
    p_erc = var_parametric_normal_parts(returns, w_erc, alpha=0.95,
                                        horizon_days=1, exposure=EXPOSURE)
    add("| Instrument | Weight (equal) | Weight (ERC) | % of VaR (equal) | % of VaR (ERC) |")
    add("|---|---:|---:|---:|---:|")
    for t, we, wr, pe, pr in zip(tickers, weights, w_erc,
                                 parts["pContrib"], p_erc["pContrib"]):
        add(f"| {t} | {we:.1%} | {wr:.1%} | {pe * 100:.1f}% | {pr * 100:.1f}% |")
    add("")
    add(f"Converged in {info['iter']} iterations; risk-contribution dispersion "
        f"{info['rc_dispersion']:.2e}. Portfolio VaR moves from ${parts['VaR']:,.0f} "
        f"to ${p_erc['VaR']:,.0f}. Contributions are equalised in variance space, so the "
        "percentage-of-VaR figures — which additionally carry the drift term — are close "
        "to but not exactly equal.")
    add("")

    # ------------------------------------------------------------------
    add("## 6. Stress scenarios")
    add("")
    eq = [c for c in tickers if c not in DEFAULT_DURATIONS]
    rate_assets = [c for c in tickers if c in DEFAULT_DURATIONS]

    eq_loss = scenario_equities_shock(returns, weights, eq, shock=-0.20, exposure=EXPOSURE)
    durations = {c: DEFAULT_DURATIONS.get(c, 0.0) for c in tickers}
    rate_res = scenario_rates_bp(returns, weights, durations=durations,
                                 bp=200.0, exposure=EXPOSURE)
    cov_res = scenario_covariance_scale(returns, weights, scale=2.0, alpha=0.99,
                                        exposure=EXPOSURE, n_sims=N_SIMS, seed=SEED)
    corr_res = scenario_corr_bump_mc(returns, weights, alpha=0.99, exposure=EXPOSURE,
                                     corr_bump_pct=50.0, n_sims=N_SIMS, seed=SEED)

    add("| Scenario | Definition | Impact |")
    add("|---|---|---:|")
    add(f"| Equity shock | {', '.join(eq)} each −20%, rate-sensitive instruments flat | "
        f"−${eq_loss:,.0f} |")
    add(f"| Rate shock | +200bp parallel; durations "
        f"{', '.join(f'{c} {durations[c]:.0f}y' for c in rate_assets) or 'n/a'}; "
        f"equities 0y | −${rate_res['loss']:,.0f} |")
    add(f"| Volatility stress | covariance ×2 (volatility ×{cov_res['vol_multiplier']:.2f}) | "
        f"VaR ${cov_res['base']['VaR']:,.0f} → ${cov_res['stressed']['VaR']:,.0f} "
        f"(+${cov_res['delta_VaR']:,.0f}) |")
    add(f"| Correlation stress | off-diagonal correlations ×1.5, volatilities held | "
        f"VaR ${corr_res['base']['VaR']:,.0f} → ${corr_res['stressed']['VaR']:,.0f} "
        f"(+${corr_res['delta_VaR']:,.0f}) |")
    add("")
    add("Equity instruments carry zero duration, so the parallel rate shock does not move "
        "them. The rate impact is attributable entirely to "
        f"{', '.join(rate_assets) if rate_assets else 'no instrument in this portfolio'}.")
    if corr_res["psd_adjusted"]:
        add("")
        add("The bumped correlation matrix required projection back onto the positive "
            "semi-definite cone.")
    add("")

    # ------------------------------------------------------------------
    add("## 7. Credit — Expected Loss")
    add("")
    cdf = pd.read_csv(DATA / "credit_example.csv")
    el, seg = compute_el_table(cdf)
    grp, totals = summarize_el(el, seg)

    add(f"| {seg} | Facilities | EAD | Expected Loss | EL / EAD |")
    add("|---|---:|---:|---:|---:|")
    for _, row in grp.iterrows():
        add(f"| {row[seg]} | {int(row['count'])} | ${row['total_EAD']:,.0f} | "
            f"${row['total_EL']:,.0f} | {row['EL_pct_of_EAD']:.2%} |")
    add(f"| **Portfolio** | **{int(totals['facilities'])}** | "
        f"**${totals['total_EAD']:,.0f}** | **${totals['total_EL']:,.0f}** | "
        f"**{totals['EL_pct_of_EAD']:.2%}** |")
    add("")
    add("Segment EL sums to portfolio EL, and portfolio EL/EAD is exposure-weighted "
        "(total EL ÷ total EAD) so it is consistent with the segment rows above it.")
    add("")

    add("### Scenario sensitivity")
    add("")
    add("| Scenario | Expected Loss | Change |")
    add("|---|---:|---:|")
    base_el = totals["total_EL"]
    for label, kw in (("Base", {}),
                      ("PD ×1.5", {"pd_mult": 1.5}),
                      ("PD +100bp", {"pd_add_bps": 100.0}),
                      ("LGD +10pp", {"lgd_add_pct": 10.0}),
                      ("PD ×2 and LGD ×1.25", {"pd_mult": 2.0, "lgd_mult": 1.25})):
        e, s = compute_el_table(cdf, **kw)
        _, t = summarize_el(e, s)
        delta = t["total_EL"] - base_el
        add(f"| {label} | ${t['total_EL']:,.0f} | "
            f"{'—' if label == 'Base' else f'+${delta:,.0f}'} |")
    add("")

    add("---")
    add("")
    add(f"*Regenerate with `python scripts/generate_validation_results.py`. "
        f"Last generated {date.today():%Y-%m-%d}.*")
    add("")
    return "\n".join(L)


def strip_timestamp(text: str) -> str:
    """Ignore the trailing generation date when comparing."""
    return "\n".join(ln for ln in text.splitlines() if "Last generated" not in ln)


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--check", action="store_true",
                    help="verify the committed results match the code; exit 1 on drift")
    args = ap.parse_args()

    report = build_report()

    if args.check:
        if not OUT.exists():
            print(f"FAIL: {OUT.relative_to(ROOT)} does not exist. Run without --check.")
            return 1
        if strip_timestamp(OUT.read_text()) != strip_timestamp(report):
            print(f"FAIL: {OUT.relative_to(ROOT)} is out of date with the engine.\n"
                  "Run `python scripts/generate_validation_results.py` and commit the result.")
            return 1
        print(f"OK: {OUT.relative_to(ROOT)} reproduces exactly.")
        return 0

    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(report)
    print(f"Wrote {OUT.relative_to(ROOT)} ({len(report.splitlines())} lines)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
